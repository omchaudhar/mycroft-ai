"""Produce the evidence pack.

Everything in outputs/ is written by this script. If a number appears in the
deck or the proposal and is not in outputs/, it does not belong there.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from controlplane import defects as defects_mod  # noqa: E402
from controlplane import metrics  # noqa: E402
from controlplane.contract import list_jurisdictions, list_use_cases, load_contract  # noqa: E402
from controlplane.slowlane.judge import get_judge  # noqa: E402
from data.generate import load  # noqa: E402

OUT = ROOT / "outputs"
USE_CASES = ["customer_support", "internal_knowledge", "decision_support"]


def _fmt(x, pct=False):
    if x is None:
        return "n/a"
    return f"{x * 100:.1f}%" if pct else f"{x:.3f}"


def table(counts: dict[str, metrics.Counts]) -> str:
    rows = ["| Detector | TP | FP | FN | TN | Precision | Recall | FP rate | FN rate |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for name, c in counts.items():
        if c.tp + c.fp + c.fn == 0:
            continue
        rows.append(
            f"| {name} | {c.tp} | {c.fp} | {c.fn} | {c.tn} | {_fmt(c.precision)} | "
            f"{_fmt(c.recall)} | {_fmt(c.fp_rate, True)} | {_fmt(c.fn_rate, True)} |"
        )
    return "\n".join(rows)


def main() -> int:
    OUT.mkdir(exist_ok=True)
    judge = get_judge()
    generated = load(ROOT / "data" / "traces.jsonl")
    holdout = load(ROOT / "data" / "holdout.jsonl")

    gen_pairs = metrics.run(generated, "IN")
    hold_pairs = metrics.run(holdout, "IN")
    gen_counts = metrics.counts_by_family(gen_pairs)
    hold_counts = metrics.counts_by_family(hold_pairs)
    lat = metrics.latency(gen_pairs)

    # Jurisdiction matrix: the same traces, three policy packs.
    matrix = {}
    for j in list_jurisdictions():
        pairs = metrics.run(generated, j)
        matrix[j] = {
            "action_mix": metrics.action_mix(pairs),
            "contracts": {uc: load_contract(uc, j).version for uc in USE_CASES},
        }

    sweeps = {
        "customer_support/hallucination": metrics.threshold_sweep(
            generated, "hallucination", "customer_support"),
        "customer_support/pii": metrics.threshold_sweep(generated, "pii", "customer_support"),
        "decision_support/bias": metrics.threshold_sweep(generated, "bias", "decision_support"),
    }

    contracts = {uc: load_contract(uc, "IN") for uc in USE_CASES}
    defect_list = defects_mod.cluster(gen_pairs, contracts)

    # ---------------- write ------------------------------------------
    (OUT / "metrics.json").write_text(json.dumps({
        "judge_backend": judge.name,
        "judge_description": judge.describes_itself_as,
        "generated": {"n": len(generated), "counts": metrics.as_dict(gen_counts),
                      "action_mix": metrics.action_mix(gen_pairs)},
        "holdout": {"n": len(holdout), "counts": metrics.as_dict(hold_counts),
                    "action_mix": metrics.action_mix(hold_pairs)},
        "latency": lat,
        "jurisdiction_matrix": matrix,
        "threshold_sweeps": sweeps,
    }, indent=2))

    (OUT / "latency.json").write_text(json.dumps(lat, indent=2))
    (OUT / "defects.json").write_text(json.dumps(
        [d.as_dict() for d in defect_list], indent=2))

    lines: list[str] = []
    w = lines.append
    w("# Measured results\n")
    w("Generated by `python scripts/run_eval.py`. Every figure below is reproducible "
      "from a clean clone with no API key.\n")
    w(f"- Judge backend: **{judge.name}** ({judge.describes_itself_as})")
    w(f"- Generated corpus: **{len(generated)} traces** across 3 use cases")
    w(f"- Hand-written adversarial holdout: **{len(holdout)} traces**")
    w("- Jurisdiction for the headline tables: **IN**\n")

    w("## Detection quality, generated corpus\n")
    w(table(gen_counts))
    w("")
    w("## Detection quality, hand-written holdout\n")
    w("Written after the detectors were built, to test the risk rather than the templates.\n")
    w(table(hold_counts))
    w("")

    w("## Latency\n")
    w("Detector compute only, measured in-process; excludes network and serialisation. "
      "The Fast Lane is the only part that runs inline on a user-facing response.\n")
    w("| Lane | p50 | p95 | p99 | max |")
    w("|---|---:|---:|---:|---:|")
    for lane in ("fast_lane_ms", "slow_lane_ms"):
        d = lat[lane]
        w(f"| {lane.replace('_ms', '').replace('_', ' ')} | {d['p50']} ms | {d['p95']} ms | "
          f"{d['p99']} ms | {d['max']} ms |")
    budget = contracts["customer_support"].latency_budget_ms
    w(f"\nFast Lane p95 is {lat['fast_lane_ms']['p95']} ms against a contract budget of "
      f"{budget} ms.\n")

    w("## The same traces under three policy packs\n")
    w("No code changes between these rows -- only the jurisdiction's policy pack.\n")
    w("| Jurisdiction | allow | log | human_review | block |")
    w("|---|---:|---:|---:|---:|")
    for j, d in matrix.items():
        m = d["action_mix"]
        w(f"| {j} | {m.get('allow', 0)} | {m.get('log', 0)} | {m.get('human_review', 0)} | "
          f"{m.get('block', 0)} |")
    w("")

    w("## The false-positive / false-negative trade-off\n")
    w("Each block re-runs one detector at each sensitivity. The point is not that one "
      "setting is best, but that the cost of each is measurable before a contract is signed.\n")
    for key, rows in sweeps.items():
        w(f"### {key}\n")
        w("| Mode | TP | FP | FN | Precision | Recall | FP rate | Flagged for review or block |")
        w("|---|---:|---:|---:|---:|---:|---:|---:|")
        for r in rows:
            w(f"| {r['mode']} | {r['tp']} | {r['fp']} | {r['fn']} | {_fmt(r['precision'])} | "
              f"{_fmt(r['recall'])} | {_fmt(r['fp_rate'], True)} | {r['blocked_or_reviewed']} |")
        w("")

    w("## Priced defects\n")
    w("Occurrence rates are measured on the corpus; rupee figures apply the assumptions in "
      "each use case's contract. Both are shown so the arithmetic can be checked.\n")
    w("| Defect | Use case | Signature | Occurrences | Escaped | Est. cost / month |")
    w("|---|---|---|---:|---:|---:|")
    for d in defect_list[:12]:
        w(f"| {d.defect_id} | {d.use_case} | `{d.signature}` | {d.occurrences} | {d.escaped} | "
          f"Rs {d.impact.total_inr:,.0f} |")
    w("")
    w("Worked example for the largest defect:\n")
    top = defect_list[0]
    w(f"> **{top.defect_id}** -- {top.title}  \n> {top.impact.formula}  \n"
      f"> = Rs {top.impact.rework_inr:,.0f} rework + Rs {top.impact.handoff_inr:,.0f} handoffs "
      f"+ Rs {top.impact.churn_inr:,.0f} churn exposure = "
      f"**Rs {top.impact.total_inr:,.0f} / month**\n")

    (OUT / "metrics.md").write_text("\n".join(lines) + "\n")

    print(f"judge backend      : {judge.name}")
    print(f"generated corpus   : {len(generated)} traces")
    print(f"holdout corpus     : {len(holdout)} traces")
    print()
    for label, counts in (("generated", gen_counts), ("holdout", hold_counts)):
        print(f"--- {label} ---")
        for name, c in counts.items():
            if c.tp + c.fp + c.fn == 0:
                continue
            print(f"  {name:15s} P={_fmt(c.precision)} R={_fmt(c.recall)} "
                  f"FP={c.fp:3d} FN={c.fn:3d}  (FPR {_fmt(c.fp_rate, True)}, "
                  f"FNR {_fmt(c.fn_rate, True)})")
    print()
    print(f"fast lane p95      : {lat['fast_lane_ms']['p95']} ms "
          f"(budget {budget} ms)")
    print(f"slow lane p95      : {lat['slow_lane_ms']['p95']} ms")
    print(f"defects clustered  : {len(defect_list)}")
    print()
    print("wrote outputs/metrics.md, metrics.json, latency.json, defects.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
